"""Refresh the actual ontology graph and prove its Gold-backed business path."""
import json
import time
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

from fabric.deploy import preflight, validate_config
from fabric.rest import DeploymentError, FabricClient

ROOT = Path(__file__).resolve().parents[1]
SKILL = "fabriciq-ontology-cli"


def main():
    cfg = validate_config(json.loads((ROOT / "fabric" / "config.live.local.json").read_text()), "check")
    client = FabricClient(cfg["tenant_id"])
    ws = preflight(cfg, client)["id"]
    graphs = [item for item in client.list(f"/v1/workspaces/{ws}/items", SKILL)
              if item["type"] == "GraphModel" and item["displayName"].startswith("MSFlixBusiness_graph_")]
    if len(graphs) != 1:
        raise DeploymentError("Expected one graph generated by the MSFlix ontology")
    graph = graphs[0]
    jobs_path = f"/v1/workspaces/{ws}/items/{graph['id']}/jobs/instances"
    active = [job for job in client.list(jobs_path, SKILL) if job["status"] in ("NotStarted", "InProgress")]
    if len(active) > 1:
        raise DeploymentError("Multiple active graph jobs; refusing another refresh")
    if active:
        location = jobs_path + "/" + active[0]["id"]
        delay = 20
    else:
        status, headers, _ = client.request("POST",
            f"/v1/workspaces/{ws}/graphModels/{graph['id']}/jobs/refreshGraph/instances", skill=SKILL)
        location = headers.get("location", "")
        if status != 202 or urlparse(location).netloc != "api.fabric.microsoft.com":
            raise DeploymentError("Graph refresh outcome ambiguous; inspect its jobs before retrying")
        delay = max(1, int(headers.get("retry-after", 20)))
    evidence = {"graph_id": graph["id"], "job_id": location.rstrip("/").split("/")[-1],
                "started_at": datetime.now(timezone.utc).isoformat(), "state": "submitted"}
    path = ROOT / "fabric" / "evidence" / "ontology-graph-refresh.json"
    path.write_text(json.dumps(evidence, indent=2) + "\n")
    print(json.dumps(evidence), flush=True)
    deadline = time.monotonic() + 1800
    while time.monotonic() < deadline:
        time.sleep(delay)
        job = client.request("GET", location, skill=SKILL)[2]
        evidence.update(state=job["status"], failure=job.get("failureReason"))
        path.write_text(json.dumps(evidence, indent=2) + "\n")
        if job["status"] == "Completed":
            break
        if job["status"] in ("Failed", "Cancelled", "Canceled", "Deduped"):
            raise DeploymentError(f"Graph refresh {job['status']}: {job.get('failureReason')}")
        delay = 20
    else:
        raise DeploymentError("Graph refresh deadline exceeded; no duplicate was submitted")
    result = client.request("POST",
        f"/v1/workspaces/{ws}/graphModels/{graph['id']}/executeQuery?beta=true",
        {"query": "MATCH (c:customer)-[:customer_order]->(r:rental)-[:order_offer]->(o:offer)-[:offer_content]->(f:content) RETURN c.customer_key AS customer_key, r.order_id AS order_id, f.content_key AS content_key LIMIT 5"},
        SKILL)[2]
    evidence["query"] = result
    path.write_text(json.dumps(evidence, indent=2) + "\n")
    print(json.dumps(evidence), flush=True)


if __name__ == "__main__":
    main()
